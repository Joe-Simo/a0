const sha = (bytes: string | Uint8Array) => createHash('sha256').update(bytes).digest('hex');
// One exported empty function and one mutable i32 stack global, initially 16; no imports/calls.
const REDUCED_ARENA = new Uint8Array([
  0, 97, 115, 109, 1, 0, 0, 0, 1, 4, 1, 96, 0, 0, 3, 2, 1, 0, 5, 3, 1, 0, 1, 6, 6, 1, 127, 1, 65,
  16, 11, 7, 7, 1, 3, 114, 117, 110, 0, 0, 10, 4, 1, 2, 0, 11,
]);
const options = {
  wasmExports: ['exchange', 'state'],
  wasmSimd: true,
  optimize: true,
  wasmIo: { module: 'a0_arena', read: 'a0_runtime_read', write: 'a0_runtime_write' },
};

test('historical C controls allow a version banner change and reject every body change', () => {
  const body = '\nuint32_t entry(uint32_t x) { return x + 1; }\n';
  const frozenSHA = sha(SOURCE_COST_FROZEN_C_BANNER + body);
  for (const version of ['0.1.62', '0.1.63', '0.1.64']) {
    const banner = `/* Generated by A0 a0c-${version}. Exact u32/bool semantics. */`;
    assert.equal(verifySourceCostFrozenC(banner + body, frozenSHA), banner);
    assert.throws(
      () => verifySourceCostFrozenC(banner + body.replace('+ 1', '+ 2'), frozenSHA),
      /frozen output differs/,
    );
    assert.throws(
      () => verifySourceCostFrozenC(`${banner}${body}\n`, frozenSHA),
      /frozen output differs/,
    );
  }
  assert.throws(
    () => verifySourceCostFrozenC(`\n${SOURCE_COST_FROZEN_C_BANNER}${body}`, frozenSHA),
    /expected version banner/,
  );
});

async function manifests() {
  // The checked-in C manifest supplies the real closure, runtime inputs and toolchain fields.
  const native = JSON.parse(await readFile('seed/source-frontend/build.json', 'utf8'));
  const direct = {
    backend: 'direct-wasm',
    entry: native.entry,
    sourceSHA256: native.sourceSHA256,
    frontendABI: native.frontendABI,
    functionCount: native.functions,
    functions: {},
    frontendOptions: options,
    frontendSHA256: native.wasmSHA256,
    frontendBytes: native.wasmBytes,
    arenaSHA256: sha(REDUCED_ARENA),
    arenaBytes: REDUCED_ARENA.length,
    totalWasmBytes: native.wasmBytes + REDUCED_ARENA.length,
    inputs: [...native.modules, ...native.nativeInputs],
    transportStackBytes: 65536,
    transportStackProof: wasmStackBound(REDUCED_ARENA),
    transportClangFlags: ['--target=wasm32-wasi', '-O3', '-flto', '-DNDEBUG'],
    transportLinkerFlags: [
      '--no-entry',
      '--export-memory',
      '-z',
      'stack-size=65536',
      '--strip-all',
    ],
    requiredWasmFeatures: ['bulk-memory', 'simd'],
    libcSHA256: native.libcSHA256,
    builtinsSHA256: native.builtinsSHA256,
    clang: native.clang,
    linker: native.linker,
  };
  return { native, direct };
}

test('compiled-backend mode requires both explicit control paths and does not replace legacy modes', () => {
  assert.equal(sourceCostControlMode(false), 'wasm-build-options');
  assert.equal(sourceCostControlMode(false, 'artifact'), 'wasm-build-options');
  assert.equal(
    sourceCostControlMode(false, 'artifact', 'checkout'),
    'same-a0-source-separate-native-transport',
  );
  assert.equal(
    sourceCostControlMode(true, 'artifact', 'checkout'),
    'same-a0-source-compiled-backends',
  );
  for (const paths of [[], ['artifact']] as const)
    assert.throws(() => sourceCostControlMode(true, ...paths), /--cross-backend requires/);
  assert.throws(
    () => sourceCostControlMode(false, undefined, 'checkout'),
    /requires --control-artifact/,
  );
});

test('compiled backends preserve source/runtime/toolchain controls while recording backend differences', async () => {
  const { native, direct } = await manifests();
  verifySourceCostControl(direct, native, 'compiled-backends');
  verifySourceCostControl(native, direct, 'compiled-backends');
  for (const legacy of [false, true])
    assert.throws(
      () => verifySourceCostControl(direct, native, legacy),
      /direct frontend requires/,
    );
  assert.throws(
    () => verifySourceCostControl(direct, direct, 'compiled-backends'),
    /one direct and one C/,
  );
  for (const field of [
    'entry',
    'sourceSHA256',
    'frontendABI',
    'libcSHA256',
    'builtinsSHA256',
    'clang',
    'linker',
  ])
    assert.throws(
      () => verifySourceCostControl({ ...direct, [field]: 'changed' }, native, 'compiled-backends'),
      new RegExp(field),
    );
  assert.throws(
    () =>
      verifySourceCostControl(
        { ...direct, functionCount: native.functions + 1 },
        native,
        'compiled-backends',
      ),
    /function count/,
  );
  for (const path of [
    'tools/native/arena_runtime.c',
    'tools/native/arena_runtime.h',
    native.modules[0].path,
  ]) {
    const changed = direct.inputs.map((input) =>
      input.path === path ? { ...input, sha256: sha('changed') } : input,
    );
    assert.throws(
      () => verifySourceCostControl({ ...direct, inputs: changed }, native, 'compiled-backends'),
      /control differs/,
    );
  }
  assert.throws(
    () =>
      verifySourceCostControl(
        {
          ...direct,
          inputs: direct.inputs.filter((input) => input.path !== native.modules[0].path),
        },
        native,
        'compiled-backends',
      ),
    /module closure/,
  );
  for (const field of [
    'frontendOptions',
    'requiredWasmFeatures',
    'transportStackBytes',
    'transportClangFlags',
    'transportLinkerFlags',
    'transportStackProof',
  ])
    assert.throws(
      () => verifySourceCostControl({ ...direct, [field]: undefined }, native, 'compiled-backends'),
      /missing|unrecorded/,
    );
  for (const field of [
    'aggregateBytes',
    'stackBytes',
    'clangFlags',
    'requiredWasmFeatures',
    'optimization',
    'symbols',
    'symbolFlags',
  ])
    assert.throws(
      () => verifySourceCostControl(direct, { ...native, [field]: undefined }, 'compiled-backends'),
      /unrecorded/,
    );
});

test('component accounting and frontend options reject incomplete or ambiguous manifests', async () => {
  const { native, direct } = await manifests();
  assert.equal(sourceCostComponents(native).length, 1);
  assert.equal(sourceCostComponents(direct).length, 2);
  assert.throws(
    () => sourceCostComponents({ ...direct, totalWasmBytes: direct.frontendBytes }),
    /total Wasm size/,
  );
  assert.throws(
    () => sourceCostComponents({ ...direct, arenaSHA256: undefined }),
    /arena.wasm hash/,
  );
  assert.throws(() => sourceCostComponents({ ...direct, arenaBytes: -1 }), /arena.wasm size/);
  assert.throws(() => sourceCostComponents({ ...native, backend: 'unknown' }), /unsupported/);
  for (const frontendOptions of [
    null,
    {},
    { ...options, optimize: undefined },
    { ...options, wasmSimd: undefined },
    { ...options, wasmExports: ['state', 'state'] },
    { ...options, wasmIo: null },
    { ...options, cIo: 'host' },
  ])
    assert.throws(() => sourceCostFrontendOptions({ frontendOptions }), /frontendOptions/);
  for (const path of ['../outside.a0', '/outside.a0', 'compiler/../outside.a0'])
    assert.throws(
      () =>
        verifySourceCostControl(
          { ...direct, inputs: [...direct.inputs, { path, sha256: sha('x') }] },
          native,
          'compiled-backends',
        ),
      /invalid direct input/,
    );
  assert.throws(
    () =>
      verifySourceCostControl(
        { ...direct, inputs: [...direct.inputs, direct.inputs[0]] },
        native,
        'compiled-backends',
      ),
    /duplicate direct input/,
  );
});

test('transport proof guard binds the final binary, full recomputation and available stack', () => {
  const arena = REDUCED_ARENA;
  assert.ok(WebAssembly.validate(arena));
  const proof = wasmStackBound(arena);
  assert.equal(proof.maxLinearStackBytes, 0);
  assert.equal(proof.maxCallDepth, 1);
  assert.deepEqual(proof.functions, [
    {
      index: 0,
      frameBytes: 0,
      calls: [],
      globalAccesses: [],
      cumulativeFrameBytes: 0,
      maxCallDepth: 1,
    },
  ]);
  const record = {
    arenaSHA256: sha(arena),
    arenaBytes: arena.length,
    transportStackBytes: 16,
    transportStackProof: proof,
  };
  let calls = 0;
  const analyze = (bytes: Uint8Array) => {
    assert.deepEqual(bytes, arena);
    calls++;
    return wasmStackBound(bytes);
  };
  verifySourceCostStackProof(record, arena, analyze);
  assert.equal(calls, 1);
  for (const field of ['artifactSHA256', 'artifactBytes', 'maxCallDepth', 'functions'])
    assert.throws(
      () =>
        verifySourceCostStackProof(
          { ...record, transportStackProof: { ...proof, [field]: null } },
          arena,
          analyze,
        ),
      /transport stack proof differs/,
    );
  assert.throws(
    () => verifySourceCostStackProof({ ...record, transportStackProof: undefined }, arena, analyze),
    /transport stack proof differs/,
  );
  assert.throws(
    () => verifySourceCostStackProof(record, new Uint8Array([...arena, 0]), analyze),
    /arena hash differs/,
  );
  assert.throws(
    () => verifySourceCostStackProof(record, arena, () => ({ ...proof, maxLinearStackBytes: 32 })),
    /below its proven bound/,
  );
  assert.throws(
    () => verifySourceCostStackProof(record, arena, () => ({ ...proof, functions: [] })),
    /lacks function proofs/,
  );
  assert.throws(
    () =>
      verifySourceCostStackProof(record, arena, () => {
        throw new Error('unsupported module');
      }),
    /unsupported module/,
  );
});

async function directProvenanceFixture(root: string) {
  const files: Record<string, string> = {
    'compiler/source_frontend.a0':
      'use "state.a0"\nfn exchange io -> io\ninput read p0\nword at input 0\nnext at input 1\nout write next word\nret out\nend\n',
    'compiler/state.a0': 'fn state (u32x3,bool) -> (u32x3,bool)\nret p0\nend\n',
  };
  for (const path of [
    'src/wasm-words.ts',
    'tools/native/arena_runtime.c',
    'tools/native/arena_runtime.h',
    'tools/native/arena_memory.c',
    'tools/source-direct-build.ts',
    'tools/wasm-stack-bound.ts',
  ])
    files[path] = await readFile(path, 'utf8');
  for (const [path, text] of Object.entries(files)) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await writeFile(join(root, path), text);
  }
  execFileSync('git', ['init', '--quiet'], { cwd: root });
  execFileSync('git', ['add', '.'], { cwd: root });
  const linked = await link(join(root, 'compiler/source_frontend.a0'), (path) =>
    readFile(path, 'utf8'),
  );
  const frontend = Buffer.from(compile(linked.program, 'wasm', options).text, 'base64');
  const arena = new Uint8Array([0, 97, 115, 109, 1, 0, 0, 0]);
  const record: SourceCostBuild = {
    backend: 'direct-wasm',
    entry: 'compiler/source_frontend.a0',
    frontendOptions: options,
    functionCount: 2,
    sourceSHA256: sha(formatProgram(linked.program)),
    functions: {
      exchange: { params: [{ words: 1, scalar: true }], result: { words: 1, scalar: true } },
      state: { params: [{ words: 4, scalar: false }], result: { words: 4, scalar: false } },
    },
    inputs: Object.entries(files).map(([path, text]) => ({ path, sha256: sha(text) })),
    frontendSHA256: sha(frontend),
    frontendBytes: frontend.length,
    arenaSHA256: sha(arena),
    arenaBytes: arena.length,
    totalWasmBytes: frontend.length + arena.length,
  };
  const compiler = { compile, formatProgram, link };
  return { files, record, compiler, frontend, arena };
}

test('direct provenance re-emits real Wasm and rejects changed inputs, closure, ABI and compiler output', async () => {
  const root = await mkdtemp(join(tmpdir(), 'a0-source-cost-'));
  try {
    const { files, record, compiler, frontend, arena } = await directProvenanceFixture(root);
    await verifyDirectSourceCostBuild(root, record, compiler);
    const reject = (change: SourceCostBuild, message: RegExp) =>
      assert.rejects(
        verifyDirectSourceCostBuild(root, { ...record, ...change }, compiler),
        message,
      );
    await reject({ functionCount: 3 }, /function count/);
    await reject({ sourceSHA256: sha('other source') }, /artifact source/);
    await reject({ functions: {} }, /direct ABI/);
    await reject(
      { frontendOptions: { ...options, wasmIo: { ...options.wasmIo, read: 'other_read' } } },
      /direct Wasm/,
    );
    const inputs = record.inputs as { path: string; sha256: string }[];
    await reject(
      { inputs: inputs.filter((input) => input.path !== 'compiler/state.a0') },
      /dependency closure/,
    );
    await reject(
      { inputs: inputs.filter((input) => input.path !== 'src/wasm-words.ts') },
      /inventory differs/,
    );
    await writeFile(join(root, 'tools/native/arena_runtime.c'), 'changed generic transport\n');
    await assert.rejects(
      verifyDirectSourceCostBuild(root, record, compiler),
      /stale direct input tools\/native\/arena_runtime.c/,
    );
    await writeFile(
      join(root, 'tools/native/arena_runtime.c'),
      files['tools/native/arena_runtime.c'] as string,
    );
    await writeFile(join(root, 'frontend.wasm'), frontend);
    await writeFile(join(root, 'arena.wasm'), arena);
    await writeFile(join(root, 'build.json'), JSON.stringify(record));
    const snapshot = await sourceCostArtifact(root);
    assert.equal(snapshot.preload.artifactSha256, sha(Buffer.concat([frontend, arena])));
    assert.equal(snapshot.preload.componentCount, 2);
    for (const [file, bytes] of [
      ['frontend.wasm', frontend],
      ['arena.wasm', arena],
    ] as const) {
      await writeFile(join(root, file), Buffer.concat([bytes, new Uint8Array([0])]));
      await assert.rejects(sourceCostArtifact(root), new RegExp(`${file} artifact differs`));
      await writeFile(join(root, file), bytes);
    }
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test('direct provenance resolves a symlinked checkout without relaxing its exact inventory', async () => {
  const scratch = join(process.cwd(), '.a0-tmp');
  await mkdir(scratch, { recursive: true });
  const directory = await mkdtemp(join(scratch, 'source-cost-symlink-'));
  try {
    const root = join(directory, 'checkout'),
      alias = join(directory, 'checkout-alias');
    await mkdir(root);
    const { record, compiler, files } = await directProvenanceFixture(root);
    await symlink(root, alias, 'dir');
    const linked = await link(join(alias, 'compiler/source_frontend.a0'), (path) =>
      readFile(path, 'utf8'),
    );
    // Independently establish the mixed spelling that macOS /var and /private/var expose.
    assert.deepEqual(
      linked.sources.map((source) => source.path),
      [await realpath(join(root, 'compiler/state.a0')), join(alias, 'compiler/source_frontend.a0')],
    );
    await verifyDirectSourceCostBuild(alias, record, compiler);
    const inputs = record.inputs as { path: string; sha256: string }[];
    for (const change of [
      { inputs: inputs.filter((input) => input.path !== 'compiler/state.a0') },
      { inputs: [...inputs, inputs[0]] },
      { functionCount: 3 },
      { frontendSHA256: sha('different compiler output') },
    ])
      await assert.rejects(
        verifyDirectSourceCostBuild(alias, { ...record, ...change }, compiler),
        /closure|duplicate|function count|direct Wasm/,
      );
    await writeFile(
      join(root, 'src/wasm-words.ts'),
      `${files['src/wasm-words.ts']}
// changed input
`,
    );
    await assert.rejects(
      verifyDirectSourceCostBuild(alias, record, compiler),
      /stale direct input src\/wasm-words.ts/,
    );
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});
