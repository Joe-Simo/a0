// The site pages are generated by an A0 program (site/gen/sitegen.a0). Its output must be the
// committed page programs byte for byte: `bun run site` regenerates them with it, so a template,
// stylesheet or results change is committed together with the pages it produces.
test('the A0 site generator reproduces site/page.a0 and site/docs.a0', {
  skip: findClang().path === undefined ? 'clang not found' : false,
  timeout: 1_800_000,
}, async () => {
  const bin = await buildGenerator();
  for (const [tpl, out] of [
    ['site/gen/page.tpl', 'site/page.a0'],
    ['site/gen/docs.tpl', 'site/docs.a0'],
  ] as const) {
    assert.equal(await generate(bin, tpl), await readFile(out, 'utf8'), `${tpl} -> ${out}`);
  }
});

// The benchmark sections are written to be read at a glance: each chart or table has a one-sentence
// takeaway computed from results/*.json (numbers only), terms are defined in plain words, and the
// long many-language lists sit behind a disclosure that is present in the prerendered HTML.
test('the home page explains every benchmark in plain words', { timeout: 600_000 }, async () => {
  const program = (await link('site/page.a0', (f) => readFile(f, 'utf8'), { root: '.' })).program;
  const { html, text } = prerender(program);
  const takeaways: readonly RegExp[] = [
    /A0 takes \d+\.\d\dx as long as hand-written C, a geometric mean over \d+ test programs/,
    /Fastest on \d+ of \d+ test programs; on every one, A0 takes at most \d+\.\d\dx as long as the fastest language/,
    /of the other \d+ languages are more than 5% faster than A0/,
    /A0 takes \d+\.\d\d ms from launch to first result: place \d+ of \d+ languages \(1 = fastest\)/,
    /A0 \(canonical\) takes \d+ tokens: place \d+ of \d+ \(1 = fewest\), fewer than \d+ of the other \d+ languages, equal to \d+ and more than \d+\. A0 \(dense\) takes \d+: place \d+, fewer than \d+, equal to \d+, more than \d+; its lossless form, with the same ids and node order, takes \d+: place \d+/,
    /Over a session of 10 edits, A0 \(canonical\) costs \d+ tokens per task: place \d+ of \d+ \(1 = fewest\), cheaper than \d+ of the other \d+ languages, equal to \d+, dearer than \d+\. A0 \(dense, lean view with callee bodies\) costs \d+: place \d+, cheaper than \d+, equal to \d+, dearer than \d+/,
    /the dense primer is larger \(\d+ tokens against \d+ for canonical\)/,
    /At 4000 functions an A0 edit costs \d+ tokens against \d+ for TypeScript, which is \d+\.\dx fewer than TypeScript/,
    /A0's checker takes \d+\.\d\d ms: place \d+ of \d+ \(1 = fastest\)/,
    /Checking and running takes A0 \d+\.\d\d ms: place \d+ of \d+ \(1 = fastest\)/,
    /A0 --parallel is the fastest implementation on \d+ of \d+ test programs/,
    /A0's scoped view is \d+\.\dx fewer tokens than reading the whole life\.a0 file in A0/,
  ];
  for (const re of takeaways) assert.match(text, re);
  // Plain labels: "test program" is defined, the table says what a place and a ratio are.
  for (const needle of [
    'A test program is one small function',
    "A0's place (1 = fastest)",
    'Fastest language other than A0',
    'A0 takes this many times as long',
    'How long each language takes, as a multiple of A0',
  ])
    assert.ok(text.includes(needle), `missing: ${needle}`);
  for (const gone of ['A0 rank', 'A0 vs fastest other', 'fastest other\n'])
    assert.ok(!text.includes(gone), `unexplained label is back: ${gone}`);
  // One disclosure per many-language chart (speed, startup, tokens, edit cost, check, check and run), closed
  // by default, and the fold hides no language: every row is still in the document.
  const disclosures = html.match(
    /<details class="more"><summary>Show all \d+ (languages|rows \(\d+ languages, A0 in two forms\))<\/summary>/g,
  );
  assert.equal(disclosures?.length, 6);
  // A0 is plotted in both forms, never only the dense one: each token and edit-cost chart has the
  // canonical and the dense subject as separate highlighted rows, and dense is defined in one line.
  for (const label of ['A0 (canonical)', 'A0 (dense)'])
    assert.ok(
      (
        html.match(
          new RegExp(`lrow me"><span class="lbl">${label.replace(/[()]/g, '\\$&')}<`, 'g'),
        ) ?? []
      ).length >= 4,
      `${label} is a highlighted subject in the token and edit-cost charts`,
    );
  assert.ok(
    text.includes('Dense is the same program in a shorter surface form; it converts losslessly'),
  );
  const speed =
    /<details class="more"><summary>Show all (\d+) languages<\/summary>(.*?)<\/details>/s.exec(
      html,
    );
  assert.equal((speed?.[2]?.match(/class="lrow/g) ?? []).length, Number(speed?.[1]));
  assert.ok(!html.includes('<details class="more" open'));
});

// A page program must fit the A0 toolchain: a function holds at most 32768 operand pairs and a text
// literal is one per byte, so the stylesheet is spread over several functions. Splitting changes the
// program, never the page: the unsplit program (one `s 9 css` line) renders identically.
test('splitting the stylesheet over functions leaves the rendered page unchanged', {
  skip: findClang().path === undefined ? 'clang not found' : false,
  timeout: 1_800_000,
}, async () => {
  const bin = await buildGenerator();
  const dir = await mkdtemp(join(tmpdir(), 'a0-sitegen-'));
  try {
    for (const name of ['page', 'docs'] as const) {
      const tpl = await readFile(`site/gen/${name}.tpl`, 'utf8');
      const unsplit = tpl.replace(/\{css_a\n[\s\S]*?\{css_d\ns 9 css 27000\n\}\n/, 's 9 css\n');
      assert.notEqual(unsplit, tpl, `${name}.tpl has the css section functions`);
      const file = join(dir, `${name}.tpl`);
      await writeFile(file, unsplit);
      const whole = await generate(bin, file, { budget: false });
      const split = await generate(bin, `site/gen/${name}.tpl`);
      assert.ok(
        functionBudgets(whole).some((f) => f.operands > OPERAND_LIMIT),
        `${name}: the unsplit program is over the budget`,
      );
      assert.ok(functionBudgets(split).every((f) => f.operands <= OPERAND_LIMIT / 1.5));
      const a = await rendered(whole);
      const b = await rendered(split);
      assert.deepEqual(b.words, a.words, `${name}: protocol stream`);
      assert.equal(b.html, a.html, `${name}: prerendered HTML`);
      assert.equal(b.text, a.text, `${name}: prerendered text`);
      assert.equal(b.css, a.css, `${name}: stylesheet`);
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('the generator refuses a function above 75% of the operand table, naming it', () => {
  const big = `fn session io -> u32\nx text "${'a'.repeat(OPERAND_LIMIT + 1)}"\nret 0\nend\n`;
  assert.throws(
    () => checkOperandBudget(big, 'page.tpl'),
    /page\.tpl: session has \d+ operand pairs, above 24576/,
  );
  checkOperandBudget(
    `fn session io -> u32\nx text "${'a'.repeat(1000)}"\nret 0\nend\n`,
    'page.tpl',
  );
});

async function rendered(
  source: string,
): Promise<{ words: number[]; html: string; text: string; css: string }> {
  const dir = await mkdtemp(join(tmpdir(), 'a0-sitegen-'));
  try {
    await writeFile(join(dir, 'p.a0'), source);
    await copyFile('site/ui.a0', join(dir, 'ui.a0'));
    const program = (await link(join(dir, 'p.a0'), (f) => readFile(f, 'utf8'), { root: dir }))
      .program;
    const io = makeIo([0, 0, 0, 0, 0]);
    run(program.byName.get('session') as TypedFunc, [io]);
    return { words: [...io.output], ...renderWords(io.output) };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}
