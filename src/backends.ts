export const JAVA_CLASS = 'A0Module';

const javaType = (t: Type): string =>
  t === 'u32'
    ? 'int'
    : t === 'bool'
      ? 'boolean'
      : t === 'io'
        ? 'A0Io'
        : t.kind === 'arr'
          ? `${javaType(t.elem)}[]`
          : `R_${mangleType(t)}`;

/** Java io runtime with the C runtime's fixed capacities: input truncated to inCap words, writes past outCap dropped. */
const javaIoRuntime = (inCap: number, outCap: number): string => `  public static final class A0Io {
    public final int[] input = new int[${inCap}]; public final int ninput; public int position; public final int[] output = new int[${outCap}]; public int noutput;
    public A0Io(int[] in) { ninput = Math.min(in.length, ${inCap}); System.arraycopy(in, 0, input, 0, ninput); }
  }
  static R_r2_u_io read(A0Io t) { int v = t.position < t.ninput ? t.input[t.position++] : 0; return new R_r2_u_io(v, t); }
  static A0Io write(A0Io t, int v) { if (t.noutput < ${outCap}) t.output[t.noutput++] = v; return t; }
  static A0Io puts(A0Io t, int[] a) { write(t, a.length); for (int v : a) write(t, v); return t; }`;

/** Nested record declarations and copy-on-write helpers for one aggregate type. */
function javaTypeDecl(t: Type): string {
  if (isPrimitive(t)) return '';
  const m = mangleType(t);
  if (t.kind === 'arr') {
    const jt = javaType(t);
    const e = javaType(t.elem);
    return `  static ${jt} set_${m}(${jt} a, int i, ${e} v) { ${jt} c = a.clone(); c[Integer.remainderUnsigned(i, ${t.length})] = v; return c; }`;
  }
  const name = javaType(t);
  const comps = t.fields.map((f, i) => `${javaType(f)} f${i}`).join(', ');
  const puts = t.fields.map((f, i) => {
    const args = t.fields.map((_, k) => (k === i ? 'v' : `r.f${k}()`)).join(', ');
    return `  static ${name} put_${m}_${i}(${name} r, ${javaType(f)} v) { return new ${name}(${args}); }`;
  });
  return [`  record ${name}(${comps}) {}`, ...puts].join('\n');
}

/** Java aggregate literal (arrays need the full nested element type in `new`). */
function javaNew(t: Type, args: readonly string[]): string {
  if (isPrimitive(t)) throw new A0Error('javaNew on primitive');
  if (t.kind === 'arr') return `new ${javaType(t)}{${args.join(', ')}}`;
  return `new ${javaType(t)}(${args.join(', ')})`;
}

function javaOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return hex(o.value);
    case 'bool':
      return o.value ? 'true' : 'false';
  }
}

function javaExpr(node: Node, fn: TypedFunc): string {
  const [a, b, c] = node.args.map(javaOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `${a} + ${b}`;
    case 'sub':
      return `${a} - ${b}`;
    case 'mul':
      return `${a} * ${b}`;
    case 'and':
      return `${a} & ${b}`;
    case 'or':
      return `${a} | ${b}`;
    case 'xor':
      return `${a} ^ ${b}`;
    case 'shl':
      return `${a} << (${b} & 31)`;
    case 'shr':
      return `${a} >>> (${b} & 31)`;
    case 'div':
      return `(${b} == 0 ? 0xffffffff : Integer.divideUnsigned(${a}, ${b}))`;
    case 'rem':
      return `(${b} == 0 ? ${a} : Integer.remainderUnsigned(${a}, ${b}))`;
    case 'eq':
      return `${a} == ${b}`;
    case 'lt':
      return `Integer.compareUnsigned(${a}, ${b}) < 0`;
    case 'le':
      return `Integer.compareUnsigned(${a}, ${b}) <= 0`;
    case 'gt':
      return `Integer.compareUnsigned(${a}, ${b}) > 0`;
    case 'ge':
      return `Integer.compareUnsigned(${a}, ${b}) >= 0`;
    case 'ne':
      return `${a} != ${b}`;
    case 'select':
      return `${a} ? ${b} : ${c}`;
    case 'call':
      return `${node.callee ?? ''}(${node.args.map(javaOperand).join(', ')})`;
    case 'arr': {
      // An all-zero scalar array is a plain allocation (Java zero-initializes); a literal of
      // 65536 elements would otherwise exceed the 64 KiB method bytecode limit.
      const t = fn.types.get(node.id) ?? 'u32';
      const zeros =
        !isPrimitive(t) &&
        t.kind === 'arr' &&
        isPrimitive(t.elem) &&
        node.args.every(
          (o) => (o.kind === 'u32' && o.value === 0) || (o.kind === 'bool' && !o.value),
        );
      if (zeros) return `new ${javaType(t)}`.replace('[]', `[${node.args.length}]`);
      return javaNew(t, node.args.map(javaOperand));
    }
    case 'rec':
      return javaNew(fn.types.get(node.id) ?? 'u32', node.args.map(javaOperand));
    case 'get':
      return `${a}[Integer.remainderUnsigned(${b}, ${arrayLength(fn, node.args[0])})]`;
    case 'set':
      return `set_${mangleType(operandTypeOf(fn, node.args[0] as Operand))}(${a}, ${b}, ${c})`;
    case 'at':
      return `${a}.f${node.args[1]?.kind === 'u32' ? node.args[1].value : 0}()`;
    case 'put':
      return `put_${mangleType(operandTypeOf(fn, node.args[0] as Operand))}_${node.args[1]?.kind === 'u32' ? node.args[1].value : 0}(${a}, ${c})`;
    case 'read':
      return `read(${a})`;
    case 'write':
      return `write(${a}, ${b})`;
    case 'puts':
      return `puts(${a}, ${b})`;
    case 'fold':
    case 'loop':
      throw new A0Error(`${node.op} is emitted as a statement`);
  }
}

const emitJavaFunction: Emitter = (fn) => {
  const params = fn.params.map((t, i) => `${javaType(t)} p${i}`).join(', ');
  const body = fn.nodes.map((n) => {
    const t = javaType(fn.types.get(n.id) ?? 'u32');
    if (n.op !== 'fold' && n.op !== 'loop') return `    final ${t} n_${n.id} = ${javaExpr(n, fn)};`;
    const [count, init, ...extra] = n.args.map(javaOperand);
    const call = [`n_${n.id}`, 'i', ...extra].join(', ');
    const guard = n.op === 'loop' ? ` if (!${n.pred ?? ''}(${call})) break;` : '';
    return `    ${t} n_${n.id} = ${init};\n    for (int i = 0; Integer.compareUnsigned(i, ${count}) < 0; i++) {${guard} n_${n.id} = ${n.callee ?? ''}(${call}); }`;
  });
  return [
    `  public static ${javaType(fn.result)} ${fn.name}(${params}) {`,
    ...body,
    `    return ${javaOperand(fn.ret)};`,
    '  }',
  ].join('\n');
};

// ---------------------------------------------------------------------------
// SystemVerilog (combinational; emitted only, see results for validation status)
// ---------------------------------------------------------------------------

export const svType = (t: Type): string =>
  t === 'bool' ? 'logic' : `logic [${bitWidth(t) - 1}:0]`;

/** Bit offset of field k inside a record (field 0 at the LSB). */
export function svFieldOffset(t: Type, k: number): number {
  if (isPrimitive(t) || t.kind !== 'rec') throw new A0Error('field offset on non-record');
  return t.fields.slice(0, k).reduce((n, f) => n + bitWidth(f), 0);
}

export function svOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return `32'd${o.value}`;
    case 'bool':
      return o.value ? "1'b1" : "1'b0";
  }
}

/** Low five bits of the shift distance; a bit-select is illegal on a literal, so mask constants here. */
function svShiftAmount(o: Operand | undefined): string {
  if (o === undefined) throw new A0Error('shift without distance');
  if (o.kind === 'u32') return `5'd${o.value & 31}`;
  return `${svOperand(o)}[4:0]`;
}

export function svExpr(node: Node, fn: TypedFunc): string {
  const [a, b, c] = node.args.map(svOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `32'(${a} + ${b})`;
    case 'sub':
      return `32'(${a} - ${b})`;
    case 'mul':
      return `32'(${a} * ${b})`;
    case 'and':
      return `${a} & ${b}`;
    case 'or':
      return `${a} | ${b}`;
    case 'xor':
      return `${a} ^ ${b}`;
    case 'shl':
      return `32'(${a} << ${svShiftAmount(node.args[1])})`;
    case 'shr':
      return `${a} >> ${svShiftAmount(node.args[1])}`;
    case 'div':
      return `(${b} == 32'd0) ? 32'hffffffff : ${a} / ${b}`;
    case 'rem':
      return `(${b} == 32'd0) ? ${a} : ${a} % ${b}`;
    case 'eq':
      return `${a} == ${b}`;
    case 'lt':
      return `${a} < ${b}`;
    case 'le':
      return `${a} <= ${b}`;
    case 'gt':
      return `${a} > ${b}`;
    case 'ge':
      return `${a} >= ${b}`;
    case 'ne':
      return `${a} != ${b}`;
    case 'select':
      return `${a} ? ${b} : ${c}`;
    case 'arr':
    case 'rec':
      // Element/field 0 occupies the least significant bits.
      return `{${[...node.args].reverse().map(svOperand).join(', ')}}`;
    case 'get': {
      const t = operandTypeOf(fn, node.args[0] as Operand);
      if (isPrimitive(t) || t.kind !== 'arr') throw new A0Error('get on non-array');
      const w = bitWidth(t.elem);
      const idx = node.args[1];
      const base =
        idx?.kind === 'u32' ? `${(idx.value % t.length) * w}` : `((${b} % ${t.length}) * ${w})`;
      return `${a}[${base} +: ${w}]`;
    }
    case 'at': {
      const t = operandTypeOf(fn, node.args[0] as Operand);
      const k = node.args[1]?.kind === 'u32' ? node.args[1].value : 0;
      if (isPrimitive(t) || t.kind !== 'rec') throw new A0Error('at on non-record');
      return `${a}[${svFieldOffset(t, k)} +: ${bitWidth(t.fields[k] as Type)}]`;
    }
    case 'set':
    case 'put':
      throw new A0Error(`${node.op} is emitted as an always_comb block`);
    case 'read':
    case 'write':
    case 'puts':
      throw new A0Error(
        `${node.op}: io effects need sequential state, which the combinational SystemVerilog backend does not implement`,
      );
    case 'call':
    case 'fold':
    case 'loop':
      throw new A0Error(`${node.op} is emitted as module instances in SystemVerilog`);
  }
}

/** Largest literal fold trip count the combinational SystemVerilog backend will unroll. */
export const SV_MAX_UNROLL = 256;

const emitSvFunction: Emitter = (fn) => {
  assertVectorSized(fn, 'SystemVerilog');
  if (needsSequential(fn)) return emitSequential(fn);
  const ports = [
    ...fn.params.map((t, i) => `  input ${svType(t)} p${i}`),
    `  output ${svType(fn.result)} result`,
  ].join(',\n');
  const decls = fn.nodes.map((n) => `  ${svType(fn.types.get(n.id) ?? 'u32')} n_${n.id};`);
  const assigns = fn.nodes.map((n) => {
    if (n.op === 'fold' || n.op === 'loop') {
      // Combinational backend: only a literal trip count can be unrolled into a chain of instances.
      const [count, init, ...extra] = n.args;
      if (count === undefined || count.kind !== 'u32') {
        throw new A0Error(
          `${fn.name}.${n.id}: ${n.op} with a non-literal trip count needs sequential state, which the combinational SystemVerilog backend does not implement`,
        );
      }
      if (count.value > SV_MAX_UNROLL) {
        throw new A0Error(
          `${fn.name}.${n.id}: ${n.op} trip count ${count.value} exceeds the SystemVerilog unroll limit ${SV_MAX_UNROLL}`,
        );
      }
      const width = svType(fn.types.get(n.id) ?? 'u32');
      const lines: string[] = [];
      let prev = init === undefined ? "32'd0" : svOperand(init);
      // For loop: done_i latches once the predicate is false; later stages pass the state through.
      let done = "1'b0";
      for (let i = 0; i < count.value; i += 1) {
        const wire = `n_${n.id}_s${i + 1}`;
        const ports = (result: string) => [
          `.p0(${prev})`,
          `.p1(32'd${i})`,
          ...extra.map((arg, k) => `.p${k + 2}(${svOperand(arg)})`),
          `.result(${result})`,
        ];
        if (n.op === 'loop') {
          const cont = `n_${n.id}_c${i}`;
          const next = `n_${n.id}_d${i + 1}`;
          const body = `n_${n.id}_b${i + 1}`;
          lines.push(
            `  logic ${cont};`,
            `  logic ${next};`,
            `  ${width} ${body};`,
            `  ${width} ${wire};`,
          );
          lines.push(`  a0_${n.pred ?? ''} u_${n.id}_p${i} (${ports(cont).join(', ')});`);
          lines.push(`  a0_${n.callee ?? ''} u_${n.id}_${i} (${ports(body).join(', ')});`);
          lines.push(`  assign ${next} = ${done} | ~${cont};`);
          lines.push(`  assign ${wire} = ${next} ? ${prev} : ${body};`);
          done = next;
        } else {
          lines.push(`  ${width} ${wire};`);
          lines.push(`  a0_${n.callee ?? ''} u_${n.id}_${i} (${ports(wire).join(', ')});`);
        }
        prev = wire;
      }
      lines.push(`  assign n_${n.id} = ${prev};`);
      return lines.join('\n');
    }
    if (n.op === 'set' || n.op === 'put') {
      const [a, b, c] = n.args.map(svOperand);
      const t = operandTypeOf(fn, n.args[0] as Operand);
      if (isPrimitive(t)) throw new A0Error(`${n.op} on primitive`);
      let slice: string;
      if (n.op === 'set') {
        if (t.kind !== 'arr') throw new A0Error('set on non-array');
        const w = bitWidth(t.elem);
        const idx = n.args[1];
        const base =
          idx?.kind === 'u32' ? `${(idx.value % t.length) * w}` : `((${b} % ${t.length}) * ${w})`;
        slice = `[${base} +: ${w}]`;
      } else {
        if (t.kind !== 'rec') throw new A0Error('put on non-record');
        const k = n.args[1]?.kind === 'u32' ? n.args[1].value : 0;
        slice = `[${svFieldOffset(t, k)} +: ${bitWidth(t.fields[k] as Type)}]`;
      }
      return `  always_comb begin n_${n.id} = ${a}; n_${n.id}${slice} = ${c}; end`;
    }
    if (n.op !== 'call') return `  assign n_${n.id} = ${svExpr(n, fn)};`;
    // A call is a combinational instance of the callee module, connected by port name.
    const conns = [...n.args.map((arg, i) => `.p${i}(${svOperand(arg)})`), `.result(n_${n.id})`];
    return `  a0_${n.callee ?? ''} u_${n.id} (${conns.join(', ')});`;
  });
  return [
    `module a0_${fn.name} (`,
    ports,
    ');',
    ...decls,
    ...assigns,
    `  assign result = ${svOperand(fn.ret)};`,
    'endmodule',
  ].join('\n');
};

