const EMITTERS: Readonly<Record<Target, Emitter>> = {
  js: emitJsFunction,
  c: emitCFunction,
  java: emitJavaFunction,
  sv: emitSvFunction,
  arm64: emitArm64Function,
  x86_64: emitX86_64Function,
  riscv64: emitRiscv64Function,
  avr: emitAvrFunction,
  wasm: emitWasmFunction,
  arm32: emitArm32Function,
};

/** True when any function of the program carries an io token anywhere in its types. */
export function usesIo(program: TypedProgram): boolean {
  return program.functions.some(
    (fn) =>
      containsIo(fn.result) ||
      fn.params.some(containsIo) ||
      [...fn.types.values()].some(containsIo),
  );
}

export function assemble(
  target: Target,
  bodies: readonly string[],
  program: TypedProgram,
  options: CompileOptions = {},
): string {
  const types = aggregateTypes(program);
  const io = usesIo(program);
  if (io && !types.some((t) => formatType(t) === '(u32,io)')) {
    types.unshift({ kind: 'rec', fields: ['u32', 'io'] });
  }
  switch (target) {
    case 'arm64':
      return assembleArm64(bodies, COMPILER_VERSION);
    case 'x86_64':
      return assembleX86_64(bodies, COMPILER_VERSION);
    case 'riscv64':
      return assembleRiscv64(bodies, COMPILER_VERSION);
    case 'avr':
      return assembleAvr(bodies, COMPILER_VERSION);
    case 'wasm':
      return Buffer.from(
        assembleWasm(
          bodies,
          program,
          {
            ioInputCapacity: options.ioInputCapacity ?? C_IO_INPUT_CAPACITY,
            ioOutputCapacity: options.ioOutputCapacity ?? C_IO_OUTPUT_CAPACITY,
          },
          COMPILER_VERSION,
        ),
      ).toString('base64');
    case 'arm32':
      return assembleArm32(bodies, COMPILER_VERSION);
    case 'js':
      return `${JS_PRELUDE}\n${bodies.join('\n\n')}\n`;
    case 'c': {
      const decls = types.map(cTypeDecl).filter((d) => d.length > 0);
      if (io)
        decls.push(
          cIoRuntime(
            options.ioInputCapacity ?? C_IO_INPUT_CAPACITY,
            options.ioOutputCapacity ?? C_IO_OUTPUT_CAPACITY,
          ),
        );
      const arena = cArenaRuntime(program);
      if (arena !== undefined) decls.push(arena);
      if (options.cParallel !== undefined) decls.push(options.cParallel.runtime);
      return `${C_PRELUDE}\n${decls.length > 0 ? `${decls.join('\n')}\n\n` : ''}${bodies.join('\n\n')}\n`;
    }
    case 'java': {
      const decls = types.map(javaTypeDecl).filter((d) => d.length > 0);
      if (io)
        decls.push(
          javaIoRuntime(
            options.ioInputCapacity ?? C_IO_INPUT_CAPACITY,
            options.ioOutputCapacity ?? C_IO_OUTPUT_CAPACITY,
          ),
        );
      return `// Generated by A0 ${COMPILER_VERSION}. int carries the u32 bit pattern.\npublic final class ${JAVA_CLASS} {\n  private ${JAVA_CLASS}() {}\n\n${decls.length > 0 ? `${decls.join('\n')}\n\n` : ''}${bodies.join('\n\n')}\n}\n`;
    }
    case 'sv':
      return `// Generated by A0 ${COMPILER_VERSION}. Pure functions combinational; io, iteration, and division clocked. Two-state semantics intended.\n\`timescale 1ns/1ps\n${bodies.some((b) => b.includes('a0_udiv ')) ? `${SV_UDIV_MODULE}\n\n` : ''}${bodies.join('\n\n')}\n`;
  }
}

export interface CompileOptions {
  readonly optimize?: boolean;
  /** C/wasm/Java/C# io capacities in words (defaults C_IO_INPUT_CAPACITY / C_IO_OUTPUT_CAPACITY); prelude only, bodies are unaffected. */
  readonly ioInputCapacity?: number;
  readonly ioOutputCapacity?: number;
  /** C target only: automatic parallel folds (src/parallel.ts `parallelC`); absent = sequential. */
  readonly cParallel?: CParallel;
}

export interface CompileResult {
  readonly text: string;
  readonly cacheHits: number;
  readonly cacheMisses: number;
}

/**
 * Bounded LRU cache of per-function emitted text. Keys include the compiler
 * version, target, optimization flag, and function content revision. This is not
 * a persistent artifact cache: the program is still validated and hashed, and the
 * module is still assembled on every call.
 */
export class FunctionCache {
  readonly #entries = new Map<string, string>();
  readonly #capacity: number;

  constructor(capacity = 1024) {
    if (!Number.isInteger(capacity) || capacity < 1)
      throw new A0Error('cache capacity must be >= 1');
    this.#capacity = capacity;
  }

  get size(): number {
    return this.#entries.size;
  }

  /** Key: compiler version, target, optimization level, and semantic revision (own content + all transitive callees). */
  static key(target: Target, optimized: boolean, fn: TypedFunc, variant = ''): string {
    return `${COMPILER_VERSION}|${target}|${optimized ? 'O1' : 'O0'}${variant}|${semanticRevision(fn)}`;
  }

  get(key: string): string | undefined {
    const value = this.#entries.get(key);
    if (value !== undefined) {
      this.#entries.delete(key);
      this.#entries.set(key, value);
    }
    return value;
  }

  set(key: string, value: string): void {
    this.#entries.delete(key);
    this.#entries.set(key, value);
    if (this.#entries.size > this.#capacity) {
      const oldest = this.#entries.keys().next().value;
      if (oldest !== undefined) this.#entries.delete(oldest);
    }
  }
}

export function emitFunction(target: Target, fn: TypedFunc, options: CompileOptions = {}): string {
  const source = options.optimize === false ? fn : optimizeFunction(fn).fn;
  // Hardware form is decided on the source function so callers and testbenches agree even
  // when optimization removes every iteration or effect.
  if (target === 'sv' && needsSequential(fn)) {
    assertVectorSized(fn, 'SystemVerilog');
    return emitSequential(source);
  }
  if (target === 'c' && options.cParallel !== undefined)
    return emitCFunction(source, options.cParallel);
  return EMITTERS[target](source);
}

export function compile(
  program: TypedProgram,
  target: Target,
  options: CompileOptions = {},
  cache?: FunctionCache,
): CompileResult {
  const optimized = options.optimize !== false;
  let cacheHits = 0;
  let cacheMisses = 0;
  const bodies = program.functions.map((fn) => {
    if (cache === undefined) return emitFunction(target, fn, options);
    const key = FunctionCache.key(
      target,
      optimized,
      fn,
      target === 'c' && options.cParallel !== undefined ? `|${options.cParallel.key}` : '',
    );
    const hit = cache.get(key);
    if (hit !== undefined) {
      cacheHits += 1;
      return hit;
    }
    cacheMisses += 1;
    const text = emitFunction(target, fn, options);
    cache.set(key, text);
    return text;
  });
  return { text: assemble(target, bodies, program, options), cacheHits, cacheMisses };
}
