function jsOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return String(o.value);
    case 'bool':
      return o.value ? 'true' : 'false';
  }
}

const FRESH_OPS = new Set<Op>(['arr', 'rec', 'set', 'put']);

function sameOp(x: Operand, y: Operand): boolean {
  return (
    (x.kind === 'node' && y.kind === 'node' && x.id === y.id) ||
    (x.kind === 'param' && y.kind === 'param' && x.index === y.index)
  );
}

/**
 * May the aggregate operand `o` be updated in place by the node at `index`?
 * Sound when the value is provably unshared: it is a fresh allocation (arr/rec/set/put result)
 * or a parameter the target owns privately (`ownedParam`: in JS only the p0 state of an
 * iteration body, in C every by-value parameter and the owned loop state); every other use of
 * it is a non-escaping element/field read (`get`/`at` as first operand) that happens before
 * `index`; and it is not returned. `get`/`at` results alias their container and are never mutated.
 */
function mutableHere(
  fn: TypedFunc,
  o: Operand,
  index: number,
  ownedParam: (paramIndex: number) => boolean,
): boolean {
  if (o.kind === 'node') {
    const def = fn.nodes.find((n) => n.id === o.id);
    if (def === undefined || !FRESH_OPS.has(def.op)) return false;
  } else if (!(o.kind === 'param' && ownedParam(o.index))) {
    return false;
  }
  if (sameOp(fn.ret, o)) return false;
  for (const [j, n] of fn.nodes.entries()) {
    if (j === index) continue;
    for (const [k, arg] of n.args.entries()) {
      if (!sameOp(arg, o)) continue;
      if (j > index) return false;
      if (!((n.op === 'get' || n.op === 'at') && k === 0)) return false;
    }
  }
  return true;
}

/** JS ownership: only the p0 state of the owned iteration-body variant is private. */
const jsOwned =
  (ownedP0: boolean) =>
  (i: number): boolean =>
    i === 0 && ownedP0;

/** A node whose result (and therefore whose and/or/xor operands) is bool. */
const isBoolNode = (fn: TypedFunc, node: Node): boolean => fn.types.get(node.id) === 'bool';

function jsExpr(node: Node, fn: TypedFunc, index = -1, ownedP0 = false): string {
  const [a, b, c] = node.args.map(jsOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `(${a} + ${b}) >>> 0`;
    case 'sub':
      return `(${a} - ${b}) >>> 0`;
    case 'mul':
      return `Math.imul(${a}, ${b}) >>> 0`;
    case 'and':
      return isBoolNode(fn, node) ? `(${a} && ${b})` : `(${a} & ${b}) >>> 0`;
    case 'or':
      return isBoolNode(fn, node) ? `(${a} || ${b})` : `(${a} | ${b}) >>> 0`;
    case 'xor':
      return isBoolNode(fn, node) ? `(${a} !== ${b})` : `(${a} ^ ${b}) >>> 0`;
    case 'shl':
      return `(${a} << (${b} & 31)) >>> 0`;
    case 'shr':
      return `${a} >>> (${b} & 31)`;
    case 'div':
      return `(${b} === 0 ? 0xffffffff : Math.floor(${a} / ${b}))`;
    case 'rem':
      return `(${b} === 0 ? ${a} : ${a} % ${b})`;
    case 'eq':
      return `${a} === ${b}`;
    case 'lt':
      return `${a} < ${b}`;
    case 'le':
      return `${a} <= ${b}`;
    case 'gt':
      return `${a} > ${b}`;
    case 'ge':
      return `${a} >= ${b}`;
    case 'ne':
      return `${a} !== ${b}`;
    case 'select':
      return `${a} ? ${b} : ${c}`;
    case 'call':
      return `a0i_${node.callee ?? ''}(${node.args.map(jsOperand).join(', ')})`;
    case 'arr': {
      // Scalar-element arrays are typed arrays (u32 -> Uint32Array, bool -> Uint8Array of 0/1);
      // nested aggregates stay plain arrays. All array helpers work on both.
      const t = fn.types.get(node.id);
      const elem = t !== undefined && !isPrimitive(t) && t.kind === 'arr' ? t.elem : 'u32';
      // An all-zero literal is a plain allocation (measured: `of(0,...)` costs on small kernels).
      const zeros = node.args.every(
        (o) => (o.kind === 'u32' && o.value === 0) || (o.kind === 'bool' && !o.value),
      );
      if (elem === 'u32')
        return zeros
          ? `new Uint32Array(${node.args.length})`
          : `Uint32Array.of(${node.args.map(jsOperand).join(', ')})`;
      if (elem === 'bool')
        return zeros
          ? `new Uint8Array(${node.args.length})`
          : `Uint8Array.of(${node.args.map((o) => `${jsOperand(o)} ? 1 : 0`).join(', ')})`;
      return `[${node.args.map(jsOperand).join(', ')}]`;
    }
    case 'rec':
      return `[${node.args.map(jsOperand).join(', ')}]`;
    case 'get': {
      const t = operandTypeOf(fn, node.args[0] as Operand);
      const elem = !isPrimitive(t) && t.kind === 'arr' ? t.elem : 'u32';
      const read = `${a}[${jsIndex(fn, node.args[0], node.args[1])}]`;
      return elem === 'bool' ? `${read} === 1` : read;
    }
    case 'set': {
      const inPlace =
        index >= 0 && mutableHere(fn, node.args[0] as Operand, index, jsOwned(ownedP0));
      const et = operandTypeOf(fn, node.args[0] as Operand);
      const boolElem = !isPrimitive(et) && et.kind === 'arr' && et.elem === 'bool';
      const value = boolElem ? `(${c} ? 1 : 0)` : c;
      const idx = jsIndex(fn, node.args[0], node.args[1]);
      return inPlace ? `(${a}[${idx}] = ${value}, ${a})` : `a0_with(${a}, ${idx}, ${value})`;
    }
    case 'at':
      return `${a}[${b}]`;
    case 'put': {
      const inPlace =
        index >= 0 && mutableHere(fn, node.args[0] as Operand, index, jsOwned(ownedP0));
      return inPlace ? `(${a}[${b}] = ${c}, ${a})` : `a0_with(${a}, ${b}, ${c})`;
    }
    case 'read':
      return `a0_read(${a})`;
    case 'write':
      return `a0_write(${a}, ${b})`;
    case 'puts':
      return `a0_puts(${a}, ${b})`;
    case 'fold':
    case 'loop':
      throw new A0Error(`${node.op} is emitted as a statement`);
  }
}

/** Emit one JS function body; `owned` marks the p0-owned iteration-body variant. */
function jsBody(fn: TypedFunc, owned: boolean): string[] {
  const stateAggregate = (o: Operand): boolean => !isPrimitive(operandTypeOf(fn, o));
  const body = fn.nodes.map((n, index) => {
    if (n.op !== 'fold' && n.op !== 'loop')
      return `  const n_${n.id} = ${jsExpr(n, fn, index, owned)};`;
    const [count, init, ...extra] = n.args.map(jsOperand);
    const call = [`n_${n.id}`, 'i', ...extra].join(', ');
    const guard = n.op === 'loop' ? ` if (!a0i_${n.pred ?? ''}(${call})) break;` : '';
    // Aggregate state is owned by the loop so the body may update it in place: copy the initial
    // value once unless it is already provably unshared (fresh and used only here; an initial
    // value passed again as an extra is read by every trip).
    const initOwned =
      mutableHere(fn, n.args[1] as Operand, index, jsOwned(owned)) &&
      !n.args.slice(2).some((o) => sameOp(o, n.args[1] as Operand));
    const initExpr = stateAggregate(n.args[1] as Operand) && !initOwned ? `${init}.slice()` : init;
    const bodyName = stateAggregate(n.args[1] as Operand)
      ? `a0o_${n.callee ?? ''}`
      : `a0i_${n.callee ?? ''}`;
    return `  let n_${n.id} = ${initExpr};\n  for (let i = 0; i < ${count}; i++) {${guard} n_${n.id} = ${bodyName}(${call}); }`;
  });
  // An owned variant must return an owned value: copy unless the result is p0 itself or fresh.
  const ret = fn.ret;
  const fresh =
    (ret.kind === 'param' && ret.index === 0) ||
    (ret.kind === 'node' && FRESH_OPS.has(fn.nodes.find((n) => n.id === ret.id)?.op ?? 'mov'));
  const retExpr =
    owned && !isPrimitive(fn.result) && !fresh ? `${jsOperand(ret)}.slice()` : jsOperand(ret);
  return [...body, `  return ${retExpr};`];
}

const emitJsFunction: Emitter = (fn) => {
  const params = fn.params.map((_, i) => `p${i}`).join(', ');
  // Public entry: validate inputs once, then run the unguarded internal function.
  // Internal calls, folds, and loops target the a0i_/a0o_ variants, so guards are paid only at the boundary.
  // Scalar guards are a single comparison: `(v >>> 0) === v` holds exactly for integers in
  // [0, 2^32) and for no string, boolean, object, NaN, or fraction (measured: the call into
  // a0_u32 cost 1.3-1.4x on three-operation kernels).
  const guards = fn.params.map((t, i) =>
    t === 'u32'
      ? `  if ((p${i} >>> 0) !== p${i}) a0_bad('p${i}', 'u32');`
      : t === 'bool'
        ? `  if (typeof p${i} !== 'boolean') a0_bad('p${i}', 'bool');`
        : `  p${i} = a0_check(p${i}, ${jsShape(t)}, 'p${i}');`,
  );
  const lines = [`function a0i_${fn.name}(${params}) {`, ...jsBody(fn, false), '}'];
  const p0 = fn.params[0];
  if (p0 !== undefined && !isPrimitive(p0) && fn.params[1] === 'u32') {
    // Iteration-body shape (state, index, ...): owned-state variant for fold/loop.
    lines.push(`function a0o_${fn.name}(${params}) {`, ...jsBody(fn, true), '}');
  }
  // Scalar-signature entries carry the body after the guards instead of calling a0i_: one frame
  // fewer at the boundary (aggregate entries keep the call, their guards rebind the parameters).
  const scalar = fn.params.every(isPrimitive);
  lines.push(
    `export function ${fn.name}(${params}) {`,
    ...guards,
    ...(scalar ? jsBody(fn, false) : [`  return a0i_${fn.name}(${params});`]),
    '}',
  );
  return lines.join('\n');
};

