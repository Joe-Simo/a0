/**
 * Source emission for JavaScript (ES module), C (C-compatible, also valid C++),
 * Java, and SystemVerilog, plus a bounded in-memory function-emission cache.
 *
 * Every backend preserves the exact v0.1 semantics: wrapping u32 arithmetic,
 * logical right shift, shift distance masked to five bits, unsigned comparison,
 * and non-numeric booleans. Identifiers are validated by the core and emitted with
 * a prefix so source names cannot collide with target keywords or runtime symbols.
 */

import {
  A0Error,
  type Node,
  type Operand,
  type Type,
  type TypedFunc,
  type TypedProgram,
} from './core.js';
import { semanticRevision } from './edit.js';
import { optimizeFunction } from './optimize.js';

export const COMPILER_VERSION = 'a0c-0.1.0';

export type Target = 'js' | 'c' | 'java' | 'sv';
export const TARGETS: readonly Target[] = ['js', 'c', 'java', 'sv'];

export function isTarget(text: string): text is Target {
  return (TARGETS as readonly string[]).includes(text);
}

const hex = (v: number): string => `0x${v.toString(16).padStart(8, '0')}`;

type Emitter = (fn: TypedFunc) => string;

// ---------------------------------------------------------------------------
// JavaScript
// ---------------------------------------------------------------------------

const JS_PRELUDE = `// Generated by A0 ${COMPILER_VERSION}. Exact u32/bool semantics.
const U32_MAX = 0xffffffff;
function a0_u32(v, name) {
  if (typeof v !== 'number' || !Number.isInteger(v) || v < 0 || v > U32_MAX) throw new RangeError(name + ': expected u32');
  return v;
}
function a0_bool(v, name) {
  if (typeof v !== 'boolean') throw new TypeError(name + ': expected bool');
  return v;
}
`;

function jsOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return String(o.value);
    case 'bool':
      return o.value ? 'true' : 'false';
  }
}

function jsExpr(node: Node): string {
  const [a, b, c] = node.args.map(jsOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `(${a} + ${b}) >>> 0`;
    case 'sub':
      return `(${a} - ${b}) >>> 0`;
    case 'mul':
      return `Math.imul(${a}, ${b}) >>> 0`;
    case 'and':
      return `(${a} & ${b}) >>> 0`;
    case 'or':
      return `(${a} | ${b}) >>> 0`;
    case 'xor':
      return `(${a} ^ ${b}) >>> 0`;
    case 'shl':
      return `(${a} << (${b} & 31)) >>> 0`;
    case 'shr':
      return `${a} >>> (${b} & 31)`;
    case 'eq':
      return `${a} === ${b}`;
    case 'lt':
      return `${a} < ${b}`;
    case 'select':
      return `${a} ? ${b} : ${c}`;
    case 'call':
      return `${node.callee ?? ''}(${node.args.map(jsOperand).join(', ')})`;
  }
}

const emitJsFunction: Emitter = (fn) => {
  const params = fn.params.map((_, i) => `p${i}`).join(', ');
  const guards = fn.params.map((t, i) => `  a0_${t}(p${i}, 'p${i}');`);
  const body = fn.nodes.map((n) => `  const n_${n.id} = ${jsExpr(n)};`);
  return [
    `export function ${fn.name}(${params}) {`,
    ...guards,
    ...body,
    `  return ${jsOperand(fn.ret)};`,
    '}',
  ].join('\n');
};

// ---------------------------------------------------------------------------
// C (also compiles as C++)
// ---------------------------------------------------------------------------

const C_PRELUDE = `/* Generated by A0 ${COMPILER_VERSION}. Exact u32/bool semantics. */
#include <stdint.h>
#include <stdbool.h>
`;

const cType = (t: Type): string => (t === 'u32' ? 'uint32_t' : 'bool');

function cOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return `${o.value}u`;
    case 'bool':
      return o.value ? 'true' : 'false';
  }
}

function cExpr(node: Node): string {
  const [a, b, c] = node.args.map(cOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `(uint32_t)(${a} + ${b})`;
    case 'sub':
      return `(uint32_t)(${a} - ${b})`;
    case 'mul':
      return `(uint32_t)((uint64_t)${a} * (uint64_t)${b})`;
    case 'and':
      return `(${a} & ${b})`;
    case 'or':
      return `(${a} | ${b})`;
    case 'xor':
      return `(${a} ^ ${b})`;
    case 'shl':
      return `(uint32_t)(${a} << (${b} & 31u))`;
    case 'shr':
      return `(${a} >> (${b} & 31u))`;
    case 'eq':
      return `(${a} == ${b})`;
    case 'lt':
      return `(${a} < ${b})`;
    case 'select':
      return `(${a} ? ${b} : ${c})`;
    case 'call':
      return `a0_${node.callee ?? ''}(${node.args.map(cOperand).join(', ')})`;
  }
}

export function cSignature(fn: TypedFunc): string {
  const params =
    fn.params.length === 0 ? 'void' : fn.params.map((t, i) => `${cType(t)} p${i}`).join(', ');
  return `${cType(fn.result)} a0_${fn.name}(${params})`;
}

const emitCFunction: Emitter = (fn) => {
  const body = fn.nodes.map(
    (n) => `  const ${cType(fn.types.get(n.id) ?? 'u32')} n_${n.id} = ${cExpr(n)};`,
  );
  return [`${cSignature(fn)} {`, ...body, `  return ${cOperand(fn.ret)};`, '}'].join('\n');
};

// ---------------------------------------------------------------------------
// Java
// ---------------------------------------------------------------------------

export const JAVA_CLASS = 'A0Module';

const javaType = (t: Type): string => (t === 'u32' ? 'int' : 'boolean');

function javaOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return hex(o.value);
    case 'bool':
      return o.value ? 'true' : 'false';
  }
}

function javaExpr(node: Node): string {
  const [a, b, c] = node.args.map(javaOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `${a} + ${b}`;
    case 'sub':
      return `${a} - ${b}`;
    case 'mul':
      return `${a} * ${b}`;
    case 'and':
      return `${a} & ${b}`;
    case 'or':
      return `${a} | ${b}`;
    case 'xor':
      return `${a} ^ ${b}`;
    case 'shl':
      return `${a} << (${b} & 31)`;
    case 'shr':
      return `${a} >>> (${b} & 31)`;
    case 'eq':
      return `${a} == ${b}`;
    case 'lt':
      return `Integer.compareUnsigned(${a}, ${b}) < 0`;
    case 'select':
      return `${a} ? ${b} : ${c}`;
    case 'call':
      return `${node.callee ?? ''}(${node.args.map(javaOperand).join(', ')})`;
  }
}

const emitJavaFunction: Emitter = (fn) => {
  const params = fn.params.map((t, i) => `${javaType(t)} p${i}`).join(', ');
  const body = fn.nodes.map(
    (n) => `    final ${javaType(fn.types.get(n.id) ?? 'u32')} n_${n.id} = ${javaExpr(n)};`,
  );
  return [
    `  public static ${javaType(fn.result)} ${fn.name}(${params}) {`,
    ...body,
    `    return ${javaOperand(fn.ret)};`,
    '  }',
  ].join('\n');
};

// ---------------------------------------------------------------------------
// SystemVerilog (combinational; emitted only, see results for validation status)
// ---------------------------------------------------------------------------

const svType = (t: Type): string => (t === 'u32' ? 'logic [31:0]' : 'logic');

function svOperand(o: Operand): string {
  switch (o.kind) {
    case 'node':
      return `n_${o.id}`;
    case 'param':
      return `p${o.index}`;
    case 'u32':
      return `32'd${o.value}`;
    case 'bool':
      return o.value ? "1'b1" : "1'b0";
  }
}

function svExpr(node: Node): string {
  const [a, b, c] = node.args.map(svOperand);
  switch (node.op) {
    case 'mov':
      return `${a}`;
    case 'add':
      return `32'(${a} + ${b})`;
    case 'sub':
      return `32'(${a} - ${b})`;
    case 'mul':
      return `32'(${a} * ${b})`;
    case 'and':
      return `${a} & ${b}`;
    case 'or':
      return `${a} | ${b}`;
    case 'xor':
      return `${a} ^ ${b}`;
    case 'shl':
      return `32'(${a} << ${b}[4:0])`;
    case 'shr':
      return `${a} >> ${b}[4:0]`;
    case 'eq':
      return `${a} == ${b}`;
    case 'lt':
      return `${a} < ${b}`;
    case 'select':
      return `${a} ? ${b} : ${c}`;
    case 'call':
      throw new A0Error('call is emitted as a module instance in SystemVerilog');
  }
}

const emitSvFunction: Emitter = (fn) => {
  const ports = [
    ...fn.params.map((t, i) => `  input ${svType(t)} p${i}`),
    `  output ${svType(fn.result)} result`,
  ].join(',\n');
  const decls = fn.nodes.map((n) => `  ${svType(fn.types.get(n.id) ?? 'u32')} n_${n.id};`);
  const assigns = fn.nodes.map((n) => {
    if (n.op !== 'call') return `  assign n_${n.id} = ${svExpr(n)};`;
    // A call is a combinational instance of the callee module, connected by port name.
    const conns = [...n.args.map((arg, i) => `.p${i}(${svOperand(arg)})`), `.result(n_${n.id})`];
    return `  a0_${n.callee ?? ''} u_${n.id} (${conns.join(', ')});`;
  });
  return [
    `module a0_${fn.name} (`,
    ports,
    ');',
    ...decls,
    ...assigns,
    `  assign result = ${svOperand(fn.ret)};`,
    'endmodule',
  ].join('\n');
};

// ---------------------------------------------------------------------------
// Module assembly and emission cache
// ---------------------------------------------------------------------------

const EMITTERS: Readonly<Record<Target, Emitter>> = {
  js: emitJsFunction,
  c: emitCFunction,
  java: emitJavaFunction,
  sv: emitSvFunction,
};

function assemble(target: Target, bodies: readonly string[]): string {
  switch (target) {
    case 'js':
      return `${JS_PRELUDE}\n${bodies.join('\n\n')}\n`;
    case 'c':
      return `${C_PRELUDE}\n${bodies.join('\n\n')}\n`;
    case 'java':
      return `// Generated by A0 ${COMPILER_VERSION}. int carries the u32 bit pattern.\npublic final class ${JAVA_CLASS} {\n  private ${JAVA_CLASS}() {}\n\n${bodies.join('\n\n')}\n}\n`;
    case 'sv':
      return `// Generated by A0 ${COMPILER_VERSION}. Combinational, two-state semantics intended.\n${bodies.join('\n\n')}\n`;
  }
}

export interface CompileOptions {
  readonly optimize?: boolean;
}

export interface CompileResult {
  readonly text: string;
  readonly cacheHits: number;
  readonly cacheMisses: number;
}

/**
 * Bounded LRU cache of per-function emitted text. Keys include the compiler
 * version, target, optimization flag, and function content revision. This is not
 * a persistent artifact cache: the program is still validated and hashed, and the
 * module is still assembled on every call.
 */
export class FunctionCache {
  readonly #entries = new Map<string, string>();
  readonly #capacity: number;

  constructor(capacity = 1024) {
    if (!Number.isInteger(capacity) || capacity < 1)
      throw new A0Error('cache capacity must be >= 1');
    this.#capacity = capacity;
  }

  get size(): number {
    return this.#entries.size;
  }

  /** Key: compiler version, target, optimization level, and semantic revision (own content + all transitive callees). */
  static key(target: Target, optimized: boolean, fn: TypedFunc): string {
    return `${COMPILER_VERSION}|${target}|${optimized ? 'O1' : 'O0'}|${semanticRevision(fn)}`;
  }

  get(key: string): string | undefined {
    const value = this.#entries.get(key);
    if (value !== undefined) {
      this.#entries.delete(key);
      this.#entries.set(key, value);
    }
    return value;
  }

  set(key: string, value: string): void {
    this.#entries.delete(key);
    this.#entries.set(key, value);
    if (this.#entries.size > this.#capacity) {
      const oldest = this.#entries.keys().next().value;
      if (oldest !== undefined) this.#entries.delete(oldest);
    }
  }
}

export function emitFunction(target: Target, fn: TypedFunc, options: CompileOptions = {}): string {
  const source = options.optimize === false ? fn : optimizeFunction(fn).fn;
  return EMITTERS[target](source);
}

export function compile(
  program: TypedProgram,
  target: Target,
  options: CompileOptions = {},
  cache?: FunctionCache,
): CompileResult {
  const optimized = options.optimize !== false;
  let cacheHits = 0;
  let cacheMisses = 0;
  const bodies = program.functions.map((fn) => {
    if (cache === undefined) return emitFunction(target, fn, options);
    const key = FunctionCache.key(target, optimized, fn);
    const hit = cache.get(key);
    if (hit !== undefined) {
      cacheHits += 1;
      return hit;
    }
    cacheMisses += 1;
    const text = emitFunction(target, fn, options);
    cache.set(key, text);
    return text;
  });
  return { text: assemble(target, bodies), cacheHits, cacheMisses };
}
